"""Generate a small drum and tone kit as a C header, 48 kHz mono 16 bit."""
import math, random, struct

SR = 48000
random.seed(7)

def env(i, n, a=0.002, d=0.25, curve=3.0):
    t = i / SR
    at = min(1.0, t / a) if a > 0 else 1.0
    return at * math.exp(-t / d) if t > 0 else at

def kick(n=0.45):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        f = 48 + 120 * math.exp(-t * 32)          # pitch drop
        out.append(math.sin(2 * math.pi * f * t) * env(i, 0, 0.001, 0.16, 2))
    # click
    for i in range(int(SR * 0.004)):
        out[i] += random.uniform(-1, 1) * 0.35 * (1 - i / (SR * 0.004))
    return out

def snare(n=0.35):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        noise = random.uniform(-1, 1)
        body = math.sin(2 * math.pi * 185 * t) * math.exp(-t / 0.06)
        out.append((0.55 * noise * math.exp(-t / 0.11) + 0.45 * body) * 0.9)
    return out

def hat(n=0.18, open_=False):
    out, prev = [], 0.0
    d = 0.16 if open_ else 0.045
    for i in range(int(SR * n)):
        t = i / SR
        x = random.uniform(-1, 1)
        hp = x - prev                            # crude high pass
        prev = x
        out.append(hp * math.exp(-t / d) * 0.5)
    return out

def clap(n=0.25):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        burst = 0.0
        for k in (0.0, 0.011, 0.022):
            if t >= k:
                burst += math.exp(-(t - k) / 0.012)
        out.append(random.uniform(-1, 1) * burst * 0.45)
    return out

def tom(n=0.4, f0=140):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        f = f0 * (1 + 0.6 * math.exp(-t * 18))
        out.append(math.sin(2 * math.pi * f * t) * math.exp(-t / 0.13) * 0.9)
    return out

def rim(n=0.12):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        out.append((math.sin(2 * math.pi * 480 * t) * math.exp(-t / 0.012) +
                    random.uniform(-1, 1) * math.exp(-t / 0.006) * 0.4) * 0.7)
    return out

def bass(n=1.0, f0=65.41):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        v = math.sin(2 * math.pi * f0 * t) + 0.4 * math.sin(2 * math.pi * f0 * 2 * t)
        out.append(v * math.exp(-t / 0.45) * 0.55)
    return out

def chord(n=1.6, root=220.0):
    out = []
    for i in range(int(SR * n)):
        t = i / SR
        v = sum(math.sin(2 * math.pi * root * r * t) for r in (1.0, 1.26, 1.5)) / 3
        out.append(v * math.exp(-t / 0.8) * 0.5)
    return out

samples = [
    ("KICK", kick()), ("SNARE", snare()), ("HAT", hat()), ("CLAP", clap()),
    ("TOM", tom()), ("RIM", rim()), ("BASS", bass()), ("CHORD", chord()),
]

lines = ["/* generated by tools/make_kit.py - 48 kHz mono 16 bit one shots */",
         "#pragma once", "#include <stdint.h>", ""]
table = []
offset = 0
for name, data in samples:
    pcm = b"".join(struct.pack("<h", max(-32767, min(32767, int(v * 32000)))) for v in data)
    lines.append("static const int16_t kit_%s[] = {" % name.lower())
    vals = struct.unpack("<%dh" % (len(pcm) // 2), pcm)
    for i in range(0, len(vals), 16):
        lines.append("    " + ",".join(str(v) for v in vals[i:i + 16]) + ",")
    lines.append("};")
    table.append((name, len(vals)))
    offset += len(vals)

lines.append("")
lines.append("struct KitSample { const int16_t *data; uint32_t len; const char *name; };")
lines.append("static const KitSample kKit[8] = {")
for name, n in table:
    lines.append('    { kit_%s, %d, "%s" },' % (name.lower(), n, name))
lines.append("};")
open("C:/Users/matto/pibuild/samples.h", "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote samples.h", sum(n for _, n in table), "frames",
      round(sum(n for _, n in table) * 2 / 1024), "KB")
